export const ITEM_ART_IDS = Object.keys(ART);

export function itemPix(id) {
  const { rows, pal } = ART[id];
  const p = new Pix(16, 16);
  rows.forEach((row, y) => {
    for (let x = 0; x < 16; x++) {
      const c = pal[row[x]];
      if (c) p.set(x, y, c);
    }
  });
  return p;
}

export function generateItems(scene) {
  for (const id of ITEM_ART_IDS) itemPix(id).toTexture(scene, `item_${id}`);
}
